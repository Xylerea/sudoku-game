function playSound(kind) {
    if (kind === "complete") { playVictorySound(); return; }
    if (!settings.soundEffects || !("AudioContext" in window)) return;
    const audio = new AudioContext();
    const oscillator = audio.createOscillator();
    const gain = audio.createGain();
    const frequency = kind === "mistake" ? 185 : kind === "complete" ? 660 : 440;
    oscillator.frequency.value = frequency;
    oscillator.type = "sine";
    gain.gain.setValueAtTime(0.0001, audio.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.12, audio.currentTime + 0.015);
    gain.gain.exponentialRampToValueAtTime(0.0001, audio.currentTime + 0.18);
    oscillator.connect(gain);
    gain.connect(audio.destination);
    oscillator.start();
    oscillator.stop(audio.currentTime + 0.19);
    oscillator.addEventListener("ended", () => audio.close(), { once: true });
}

function renderBoard() {
    const { size, boxRows, boxCols } = gridConfig;
    board.style.setProperty('--grid-size', size);
    board.dataset.size = size;
    numberPad.dataset.size = size;
    numberPad.style.setProperty('--key-count', size);
    [...numberPad.children].forEach((button, i) => {
        button.hidden = i >= size;
        button.setAttribute('aria-label', translate('enter') + ' ' + (i + 1));
    });
    board.replaceChildren();

    puzzle.forEach((given, index) => {
        const row = Math.floor(index / size);
        const column = index % size;
        const editable = playing && !given && !completed;
        const cell = document.createElement(editable ? "input" : "span");

        cell.className = "cell";
        const wrongEntry = !given && values[index] !== 0 && values[index] !== solution[index];
        cell.classList.toggle("invalid", wrongEntry);
        cell.dataset.index = index;

        if (given) cell.classList.add("given");
        if ((column + 1) % boxCols === 0 && column < size - 1) cell.classList.add("box-right");
        if ((row + 1) % boxRows === 0 && row < size - 1) cell.classList.add("box-bottom");
        if (column === size - 1) cell.classList.add("edge-right");
        if (row === size - 1) cell.classList.add("edge-bottom");

        if (editable) {
            cell.type = "text";
            cell.inputMode = "numeric";
            cell.maxLength = 1;
            cell.autocomplete = "off";
            cell.spellcheck = false;
            cell.setAttribute("autocorrect", "off");
            cell.setAttribute("autocapitalize", "off");
            cell.disabled = paused;
            cell.setAttribute("aria-invalid", String(wrongEntry));
            if (wrongEntry) cell.setAttribute("aria-describedby", "game-status");
            cell.setAttribute(
                "aria-label",
                `${translate("row")} ${row + 1}, ${translate("column")} ${column + 1}`
            );
            cell.value = values[index] || "";
            cell.classList.toggle("selected", index === selectedIndex);

            cell.addEventListener("focus", () => {
                selectedIndex = index;
                updateSelection();
            });

            cell.addEventListener("input", () => {
                const typed = Number(cell.value.slice(-1));
                const nextValue = Number.isInteger(typed) && typed >= 1 && typed <= size ? typed : 0;
                cell.value = nextValue || "";
                setCellValue(index, nextValue);
            });

            cell.addEventListener("keydown", event => {
                const offsets = {
                    ArrowLeft: -1,
                    ArrowRight: 1,
                    ArrowUp: -size,
                    ArrowDown: size
                };

                if (!(event.key in offsets)) return;
                event.preventDefault();

                const step = offsets[event.key];
                let next = index + step;

                while (next >= 0 && next < size * size) {
                    if (Math.abs(step) === 1 &&
                        Math.floor(next / size) !== row) break;

                    const target = board.children[next];
                    if (target instanceof HTMLInputElement) {
                        target.focus();
                        break;
                    }
                    next += step;
                }
            });
        } else {
            cell.textContent = values[index] || "";
            if (playing && !completed) {
                cell.tabIndex = 0;
                cell.addEventListener('focus', () => {
                    if (paused) return;
                    selectedIndex = index;
                    updateSelection();
                });
                cell.addEventListener('click', () => cell.focus());
            }
            cell.setAttribute(
                "aria-label",
                `${translate("row")} ${row + 1}, ${translate("column")} ${column + 1}: ${values[index] || translate("empty")}`
            );
        }

        board.append(cell);
    });

    updateSelection();
}

