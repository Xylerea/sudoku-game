// Difficulty selection and gameplay share the same information drawer.
function openGameplayInformation(section) {
    if (document.querySelector('#information-dialog[open]')) return;
    const opener = document.activeElement;
    const inGameplay = document.body.classList.contains('is-playing');
    const resumeTimer = inGameplay && playing && !completed && !paused;
    if (resumeTimer) window.clearInterval(timerInterval);
    const dialog = document.createElement('dialog');
    dialog.id = 'information-dialog';
    dialog.className = 'settings-dialog';
    dialog.setAttribute('aria-labelledby', 'information-title');
    const header = document.createElement('div'); header.className = 'settings-heading';
    const title = document.createElement('h2'); title.id = 'information-title';
    title.dataset.i18n = section === '#how-to' ? 'howToPlay' : 'about';
    title.textContent = translate(title.dataset.i18n);
    const close = settingsClose.cloneNode(true); close.removeAttribute('id');
    close.removeAttribute('data-i18n-aria-label'); close.setAttribute('aria-label', translate('closeNavigation'));
    header.append(title, close);
    const content = document.createElement('div'); content.className = 'settings-content';
    // Clone the homepage source so wording and numbering stay identical.
    const source = document.querySelector(section).cloneNode(true);
    source.removeAttribute('id');
    source.querySelectorAll('[id]').forEach(element => element.removeAttribute('id'));
    if (section === '#how-to' && inGameplay) {
        // Only gameplay filters the detached copy; difficulty selection keeps all levels.
        source.querySelectorAll('.grid-instructions').forEach(instructions => {
            if (instructions.dataset.difficulty !== selectedDifficulty) {
                instructions.remove();
                return;
            }
            const size = document.createElement('span');
            size.className = 'instruction-grid-size';
            size.dir = 'ltr';
            size.textContent = gridConfig.size + '\u00d7' + gridConfig.size;
            instructions.querySelector('h3').replaceWith(size);
            // Use the restored board configuration, including older saved puzzles.
            instructions.querySelectorAll('li').forEach((rule, index) => {
                rule.textContent = sizedRule('rule' + (index + 1), gridConfig);
            });
        });
    }
    content.append(source);
    dialog.append(header, content); document.body.append(dialog);
    close.addEventListener('click', () => dialog.close());
    dialog.addEventListener('click', event => {
        const r = dialog.getBoundingClientRect();
        if (event.target === dialog && (event.clientX < r.left || event.clientX > r.right || event.clientY < r.top || event.clientY > r.bottom)) dialog.close();
    });
    dialog.addEventListener('close', () => {
        dialog.remove();
        if (resumeTimer && playing && !completed && !paused && document.body.classList.contains('is-playing')) startTimer();
        if (opener?.isConnected) opener.focus({ preventScroll: true });
    }, { once: true });
    dialog.showModal(); close.focus();
}
