// A short rising chord; unavailable or blocked audio never interrupts a win.
function playVictorySound() {
    if (!settings.soundEffects) return;
    const Audio = window.AudioContext || window.webkitAudioContext;
    if (!Audio) return;
    let audio;
    const dispose = () => {
        try { audio?.close()?.catch(() => {}); } catch {}
    };
    try {
        audio = new Audio();
        const play = () => {
            if (!settings.soundEffects || audio.state === 'closed') { dispose(); return; }
            try {
                const start = audio.currentTime + 0.02;
                [523.25, 659.25, 783.99].forEach((frequency, index) => {
                    const oscillator = audio.createOscillator();
                    const gain = audio.createGain();
                    const time = start + index * 0.11;
                    oscillator.type = 'sine';
                    oscillator.frequency.value = frequency;
                    gain.gain.setValueAtTime(0.0001, time);
                    gain.gain.exponentialRampToValueAtTime(0.07, time + 0.025);
                    gain.gain.exponentialRampToValueAtTime(0.0001, time + 0.3);
                    oscillator.connect(gain); gain.connect(audio.destination);
                    oscillator.start(time); oscillator.stop(time + 0.32);
                    if (index === 2) oscillator.addEventListener('ended', dispose, { once: true });
                });
            } catch { dispose(); }
        };
        if (audio.state === 'suspended') Promise.resolve(audio.resume()).then(play).catch(dispose);
        else play();
    } catch { dispose(); }
}

function sizedRule(key, config) {
    return translate(key).replace(/3\s*[\u00d7xX]\s*3/g, config.boxRows + '\u00d7' + config.boxCols).replace(/9/g, String(config.size));
}
