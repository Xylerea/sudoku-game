// Presentation-only active state for the shared desktop navigation.
function updateDesktopNavigation() {
    const links = document.querySelectorAll('#main-nav a');
    if (!matchMedia('(min-width: 769px)').matches) {
        links.forEach(link => link.removeAttribute('aria-current'));
        return;
    }
    let current = '#';
    if (document.body.matches('.is-playing, .is-choosing')) current = null;
    else for (const id of ['features', 'how-to']) {
        const rect = document.getElementById(id).getBoundingClientRect();
        if (rect.top < innerHeight / 2 && rect.bottom > 0) current = '#' + id;
    }
    links.forEach(link => {
        if (link.getAttribute('href') === current) link.setAttribute('aria-current', 'page');
        else link.removeAttribute('aria-current');
    });
}
new MutationObserver(updateDesktopNavigation).observe(document.body, { attributes: true, attributeFilter: ['class'] });
window.addEventListener('scroll', updateDesktopNavigation, { passive: true });
window.addEventListener('resize', updateDesktopNavigation);
